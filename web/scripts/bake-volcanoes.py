"""Bake the United States' volcanoes from the Smithsonian's Volcanoes of the World into
src/usVolcanoes.ts: the positions USGS HANS's alert levels are drawn at (HANS gives none).

The Smithsonian's WFS has no CORS, and volcanoes don't move, so this runs by hand, not in the
pipeline. Both lists: the Holocene ones, and the Pleistocene ones for calderas HANS monitors
(Long Valley, Yellowstone, Coso) that aren't in the Holocene list.

    python -I web/scripts/bake-volcanoes.py web/src/usVolcanoes.ts
"""

from __future__ import annotations

import datetime as dt
import json
import sys
import urllib.request

WFS = "https://webservices.volcano.si.edu/geoserver/GVP-VOTW/ows?service=WFS&version=2.0.0&request=GetFeature&outputFormat=application/json&typeName=GVP-VOTW:"
LISTS = {"H": "Smithsonian_VOTW_Holocene_Volcanoes", "P": "Smithsonian_VOTW_Pleistocene_Volcanoes"}


def fetch(type_name: str) -> list[dict]:
    with urllib.request.urlopen(WFS + type_name, timeout=120) as r:
        return json.load(r)["features"]


def main(out: str) -> int:
    rows: dict[int, list] = {}
    for epoch, type_name in LISTS.items():
        for f in fetch(type_name):
            p = f["properties"]
            if "United States" not in (p.get("Country") or ""):
                continue
            vnum = int(p["Volcano_Number"])
            if vnum in rows:
                continue  # Holocene first: it carries the last eruption
            lon, lat = f["geometry"]["coordinates"][:2]
            last = p.get("Last_Eruption_Year")
            rows[vnum] = [
                vnum,
                p["Volcano_Name"],
                round(float(lat), 4),
                round(float(lon), 4),
                int(p["Elevation"]) if p.get("Elevation") is not None else None,
                p.get("Primary_Volcano_Type") or "",
                int(last) if isinstance(last, (int, float)) else None,
                epoch,
            ]
    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in sorted(rows.values()))
    stamp = dt.date.today().isoformat()
    with open(out, "w", encoding="utf8", newline="\n") as f:
        f.write(
            "// Generated by web/scripts/bake-volcanoes.py from the Smithsonian's Volcanoes of the World\n"
            f"// ({stamp}): the {len(rows)} volcanoes in the United States, Holocene and Pleistocene.\n"
            "// Global Volcanism Program, Smithsonian Institution. Don't edit by hand: rerun the script.\n"
            "//\n"
            "// [volcano number, name, latitude, longitude, elevation m, type, last eruption year (negative BCE) or null,\n"
            "//  'H' Holocene / 'P' Pleistocene]\n\n"
            "export type UsVolcanoRow = readonly [number, string, number, number, number | null, string, number | null, 'H' | 'P'];\n\n"
            f"export const US_VOLCANOES: readonly UsVolcanoRow[] = [\n{body},\n];\n"
        )
    print(f"wrote {out}: {len(rows)} volcanoes ({sum(r[7] == 'H' for r in rows.values())} Holocene)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
