"""Bake the cities that fill in as the globe is zoomed (src/worldCities.ts), and the facts on
a city's card (src/cityFacts.ts, row for row), from Natural Earth's populated places, most
important first (Natural Earth's own label zoom, then metro population).

Each city carries how far it is from the nearest city drawn before it: the hand-picked ones
in cities.ts, then those above it here. cities.ts shows a city once that gap is wide enough on
screen, so zooming in only ever adds cities. The first place within 25 km of a hand-picked
city lends it its facts (gap 0); any other that close is left out. Rerun this after editing
cities.ts.

Natural Earth is public domain and its places hardly move, so this runs by hand, not in the
pipeline. Pass a path to a copy already downloaded to skip the 19 MB fetch.

    python -I web/scripts/bake-cities.py web/src [ne_10m_populated_places.geojson]
"""

from __future__ import annotations

import datetime as dt
import json
import math
import pathlib
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places.geojson"
# Natural Earth's label zoom (a web-map zoom level): ~6,900 places at 7 or less.
MAX_MIN_ZOOM = 7
NEAR_KM = 25
EARTH_KM = 6371.0
CITIES_TS = pathlib.Path(__file__).resolve().parent.parent / "src" / "cities.ts"
# What kind of place, as cities.ts reads it: 1 national capital, 2 regional capital, 3 research station.
KINDS = {
    "Admin-0 capital": 1,
    "Admin-0 capital alt": 1,
    "Admin-1 capital": 2,
    "Admin-1 region capital": 2,
    "Scientific station": 3,
}


def load(path: str | None) -> list[dict]:
    if path:
        with open(path, encoding="utf-8") as f:
            return json.load(f)["features"]
    with urllib.request.urlopen(URL, timeout=300) as r:
        return json.load(r)["features"]


def unit(lat: float, lon: float) -> tuple[float, float, float]:
    la, lo = math.radians(lat), math.radians(lon)
    return (math.cos(la) * math.cos(lo), math.cos(la) * math.sin(lo), math.sin(la))


def km(a: tuple[float, float, float], b: tuple[float, float, float]) -> float:
    return EARTH_KM * math.acos(max(-1.0, min(1.0, a[0] * b[0] + a[1] * b[1] + a[2] * b[2])))


def hand_picked() -> list[tuple[float, float, float]]:
    rows = re.findall(r"\['[^']+', (-?[\d.]+), (-?[\d.]+)\]", CITIES_TS.read_text(encoding="utf-8"))
    return [unit(float(lat), float(lon)) for lat, lon in rows]


def sig3(n: int) -> int:
    """Populations are estimates: three figures are plenty, and compress better."""
    return 0 if n <= 0 else int(round(n, 2 - int(math.log10(n))))


def main(out_dir: str, path: str | None = None) -> int:
    places = sorted(
        (f["properties"] for f in load(path) if f["properties"]["MIN_ZOOM"] <= MAX_MIN_ZOOM),
        key=lambda p: (p["MIN_ZOOM"], -(p["POP_MAX"] or 0)),
    )
    base = hand_picked()
    matched = [False] * len(base)
    drawn = list(base)
    countries: list[str] = []
    regions: list[str] = []

    def index(table: list[str], name: str) -> int:
        if name not in table:
            table.append(name)
        return table.index(name)

    rows = []
    for p in places:
        lat, lon = round(p["LATITUDE"], 2), round(p["LONGITUDE"], 2)
        u = unit(lat, lon)
        gap = min(km(u, d) for d in drawn)
        if gap < NEAR_KM:
            # The hand-picked city here, if it has no facts yet; else too close to show.
            i = min(range(len(base)), key=lambda i: km(u, base[i]))
            if matched[i] or km(u, base[i]) >= NEAR_KM:
                continue
            matched[i] = True
            gap = 0
        else:
            drawn.append(u)
        name = " ".join(p["NAME"].split())
        country = p["ADM0NAME"] or ""
        region = p["ADM1NAME"] or ""
        qid = p.get("WIKIDATAID") or ""
        rows.append(
            [
                name,
                lat,
                lon,
                p["MIN_ZOOM"],
                round(gap),
                sig3(p["POP_MAX"] or 0),
                index(countries, country),
                index(regions, region) if region and region not in (name, country) else -1,
                KINDS.get(p["FEATURECLA"], 0),
                int(qid[1:]) if re.fullmatch(r"Q\d+", qid) else 0,
            ]
        )

    unmatched = len(matched) - sum(matched)
    dumps = lambda v: json.dumps(v, ensure_ascii=False)
    row = lambda r: "  [" + ", ".join(dumps(v) if isinstance(v, str) else f"{v:g}" for v in r) + "],"
    header = [
        "// Generated by web/scripts/bake-cities.py from Natural Earth's populated places",
        f"// ({dt.date.today().isoformat()}): the {len(rows)} at label zoom {MAX_MIN_ZOOM} or less, most important first.",
        "// Natural Earth, public domain. Don't edit by hand: rerun the script (and after editing cities.ts).",
        "//",
    ]
    files = {
        "worldCities.ts": [
            *header,
            "// [name, latitude, longitude, Natural Earth's label zoom (web-map zoom level it's labelled from),",
            "//  km to the nearest city drawn before it (0: the hand-picked city here, lending its facts)]",
            "// Their facts are cityFacts.ts's rows, in the same order (loaded only when a city is opened).",
            "",
            "export type WorldCityRow = readonly [string, number, number, number, number];",
            "",
            "export const WORLD_CITIES: readonly WorldCityRow[] = [",
            *(row(r[:5]) for r in rows),
            "];",
            "",
        ],
        "cityFacts.ts": [
            *header,
            "// worldCities.ts's cities, row for row: [metro population, country (index into COUNTRIES),",
            "//  region (REGIONS, or -1), 0 place / 1 national capital / 2 regional capital / 3 research station,",
            "//  Wikidata Q-number (0: none)]",
            "",
            "export type CityFactRow = readonly [number, number, number, number, number];",
            "",
            f"export const COUNTRIES: readonly string[] = {dumps(countries)};",
            "",
            f"export const REGIONS: readonly string[] = {dumps(regions)};",
            "",
            "export const CITY_FACTS: readonly CityFactRow[] = [",
            *(row(r[5:]) for r in rows),
            "];",
            "",
        ],
    }
    for name, lines in files.items():
        with open(pathlib.Path(out_dir) / name, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
    print(f"{len(rows)} cities -> {out_dir}" + (f" ({unmatched} hand-picked with no facts)" if unmatched else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
